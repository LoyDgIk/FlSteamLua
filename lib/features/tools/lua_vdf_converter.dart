import 'dart:io';

import 'package:path/path.dart' as p;

import '../../core/task_center.dart';
import '../library/kv1.dart';

enum ConversionDirection { auto, luaToVdf, vdfToLua }

class ConversionResult {
  const ConversionResult(this.source, {this.output, this.error});
  final String source;
  final String? output;
  final String? error;
  bool get succeeded => error == null;
}

class LuaVdfConverter {
  static final _keyed = RegExp(
    r'''^\s*addappid\s*\(\s*(\d+)\s*,\s*\d+\s*,\s*["']([^"']+)["']\s*\)''',
    caseSensitive: false,
    multiLine: true,
  );
  static final _manifest = RegExp(
    r'''^\s*setManifestid\s*\(\s*(\d+)\s*,\s*["'](\d+)["']''',
    caseSensitive: false,
    multiLine: true,
  );

  String luaToVdf(String content, int appId) {
    if (appId <= 0) throw const FormatException('AppID must be positive');
    if (content.trim().isEmpty) {
      throw const FormatException('Lua content is empty');
    }
    final depots = <int, Map<String, dynamic>>{};
    for (final match in _keyed.allMatches(content)) {
      depots[int.parse(match[1]!)] = {'DecryptionKey': match[2]!.trim()};
    }
    for (final match in _manifest.allMatches(content)) {
      depots[int.parse(match[1]!)]?['Manifest'] = match[2]!;
    }
    final ids = depots.keys.toList()..sort();
    return Kv1.stringify({
      'AppState': {
        'appid': '$appId',
        'Universe': '1',
        'depots': {for (final id in ids) '$id': depots[id]},
      },
    });
  }

  String vdfToLua(
    String content, {
    int? appId,
    bool includeManifestIds = false,
  }) {
    if (content.trim().isEmpty) {
      throw const FormatException('VDF content is empty');
    }
    final root = Kv1.parse(content);
    final state = _map(root, 'AppState') ?? root;
    appId ??= int.tryParse('${_value(state, 'appid') ?? ''}');
    final depots = _map(state, 'depots') ?? _map(root, 'depots') ?? {};
    final result = StringBuffer('-- Generated by FlSteamLua\n');
    if (appId != null && appId > 0) result.writeln('addappid($appId)');
    for (final entry in depots.entries) {
      final id = int.tryParse(entry.key);
      if (id == null || id <= 0 || entry.value is! Map) continue;
      final depot = Map<String, dynamic>.from(entry.value as Map);
      final key = '${_value(depot, 'DecryptionKey') ?? ''}'.trim();
      if (key.isEmpty || key == '0') continue;
      result.writeln('addappid($id, 1, "${_escape(key)}")');
      final manifest = '${_value(depot, 'Manifest') ?? ''}';
      if (includeManifestIds && RegExp(r'^[1-9]\d*$').hasMatch(manifest)) {
        result.writeln('setManifestid($id, "$manifest", 0)');
      }
    }
    return result.toString();
  }

  Future<ConversionResult> convertFile(
    String source, {
    required String outputDirectory,
    ConversionDirection direction = ConversionDirection.auto,
    int? appId,
    bool includeManifestIds = false,
    bool overwrite = false,
  }) async {
    try {
      final extension = p.extension(source).toLowerCase();
      if (direction == ConversionDirection.auto) {
        direction = switch (extension) {
          '.lua' => ConversionDirection.luaToVdf,
          '.vdf' || '.acf' => ConversionDirection.vdfToLua,
          _ => throw const FormatException('Choose a Lua, VDF or ACF file'),
        };
      }
      final content = await File(source).readAsString();
      appId ??= int.tryParse(
        p.basenameWithoutExtension(source).replaceFirst('appmanifest_', ''),
      );
      final String output;
      final String resultExtension;
      if (direction == ConversionDirection.luaToVdf) {
        if (appId == null) {
          throw const FormatException('Specify an AppID or use <AppID>.lua');
        }
        output = luaToVdf(content, appId);
        resultExtension = '.vdf';
      } else {
        output = vdfToLua(
          content,
          appId: appId,
          includeManifestIds: includeManifestIds,
        );
        resultExtension = '.lua';
      }
      await Directory(outputDirectory).create(recursive: true);
      final target = File(
        p.join(
          outputDirectory,
          '${p.basenameWithoutExtension(source)}$resultExtension',
        ),
      );
      if (!overwrite && await target.exists()) {
        throw FileSystemException('Output already exists', target.path);
      }
      await target.writeAsString(output, flush: true);
      return ConversionResult(source, output: target.path);
    } catch (error) {
      return ConversionResult(source, error: error.toString());
    }
  }

  Future<List<ConversionResult>> convertFiles(
    List<String> files, {
    required String outputDirectory,
    ConversionDirection direction = ConversionDirection.auto,
    int? appId,
    bool includeManifestIds = false,
    bool overwrite = false,
    TaskContext? task,
  }) async {
    final results = <ConversionResult>[];
    for (var index = 0; index < files.length; index++) {
      task?.checkCancelled();
      results.add(
        await convertFile(
          files[index],
          outputDirectory: outputDirectory,
          direction: direction,
          appId: appId,
          includeManifestIds: includeManifestIds,
          overwrite: overwrite,
        ),
      );
      task?.report(p.basename(files[index]), (index + 1) / files.length);
    }
    return results;
  }

  static Object? _value(Map<String, dynamic> map, String key) {
    for (final entry in map.entries) {
      if (entry.key.toLowerCase() == key.toLowerCase()) return entry.value;
    }
    return null;
  }

  static Map<String, dynamic>? _map(Map<String, dynamic> map, String key) {
    final value = _value(map, key);
    return value is Map ? Map<String, dynamic>.from(value) : null;
  }

  static String _escape(String value) =>
      value.replaceAll(r'\', r'\\').replaceAll('"', r'\"');
}
